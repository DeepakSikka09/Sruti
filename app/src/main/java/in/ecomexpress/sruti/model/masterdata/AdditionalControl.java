package in.ecomexpress.sruti.model.masterdata;

public class AdditionalControl {
    private String control_type;
    private String display_condition;
    private String watermark;

    public String getControl_type() {
        return control_type;
    }

    public void setControl_type(String control_type) {
        this.control_type = control_type;
    }

    public String getDisplay_condition() {
        return display_condition;
    }

    public void setDisplay_condition(String display_condition) {
        this.display_condition = display_condition;
    }

    public String getWatermark() {
        return watermark;
    }

    public void setWatermark(String watermark) {
        this.watermark = watermark;
    }

}
