    public boolean isInManifestRadiusUsingLatLng(double userLat, double userLng, double manifestLat, double manifestLong, double radiusToCheckInMeters) {
        if (manifestLat == 0 && manifestLong == 0) {
            return false;
        } else {

            Location userLocation = null;
            Location destinationLocation = null;
            try {
                userLocation = new Location("");
                destinationLocation = new Location("");

                userLocation.setLatitude(userLat);
                userLocation.setLongitude(userLng);

                destinationLocation.setLatitude(manifestLat);
                destinationLocation.setLongitude(manifestLong);

                double distanceBetweenInMeters = destinationLocation.distanceTo(userLocation);

                return distanceBetweenInMeters <= radiusToCheckInMeters;
            } catch (Exception exception) {
                exception.printStackTrace();
                return false;
            }
        }
    }

