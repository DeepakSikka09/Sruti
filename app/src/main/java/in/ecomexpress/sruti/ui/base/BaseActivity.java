    public double getRadialDistanceUsingLatLng(double starLat, double startLng,
                                               double destLat, double destLng) {
        if (destLat == 0 && destLng == 0) {
            return 0;
        } else {

            Location userLocation = null;
            Location destinationLocation = null;
            try {
                userLocation = new Location("");
                destinationLocation = new Location("");

                userLocation.setLatitude(starLat);
                userLocation.setLongitude(startLng);

                destinationLocation.setLatitude(destLat);
                destinationLocation.setLongitude(destLng);
            } catch (Exception e) {
                e.printStackTrace();
            }

            return ((userLocation != null) ? userLocation.distanceTo(destinationLocation) : 0);

        }
    }

